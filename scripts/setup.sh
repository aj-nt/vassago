#!/bin/bash
# Vassago First-Run Setup
# Creates directories, generates configs, and installs launchd plists
# Usage: ./scripts/setup.sh [--daemon-only] [--agent-only] [--studio]

set -euo pipefail

DAEMON_ONLY=false
AGENT_ONLY=false
STUDIO=false

for arg in "$@"; do
    case "$arg" in
        --daemon-only) DAEMON_ONLY=true ;;
        --agent-only)  AGENT_ONLY=true ;;
        --studio)      STUDIO=true ;;
        --help|-h)
            echo "Usage: ./scripts/setup.sh [options]"
            echo ""
            echo "Options:"
            echo "  --daemon-only  Set up daemon only (no agent config)"
            echo "  --agent-only   Set up agent only (assumes daemon elsewhere)"
            echo "  --studio       Configure for Studio (always-on server)"
            echo ""
            echo "Creates:"
            echo "  ~/.vassago/              Data directory"
            echo "  ~/.vassago/config.yaml   Daemon config"
            echo "  ~/.vassago/agent.yaml    Agent config"
            echo "  ~/.vassago/screenshots/  Browser screenshots"
            echo "  ~/.vassago/agents.json    Multi-agent registry"
            echo "  ~/Library/LaunchAgents/    launchd plists (macOS)"
            exit 0
            ;;
    esac
done

VASSAGO_DIR="$HOME/.vassago"
VASSAGO_DB="$VASSAGO_DIR/vassago.db"
DAEMON_SOCKET="$VASSAGO_DIR/vassago.sock"

# Create directories
echo "Creating directories..."
mkdir -p "$VASSAGO_DIR"
mkdir -p "$VASSAGO_DIR/screenshots"
mkdir -p "$VASSAGO_DIR/agents"
mkdir -p "$VASSAGO_DIR/pastes"
mkdir -p "$VASSAGO_DIR/personalities"
mkdir -p "$VASSAGO_DIR/generated_images"

# ============================================
# Daemon Configuration
# ============================================
if [ "$AGENT_ONLY" = false ]; then
    echo "Writing daemon config to $VASSAGO_DIR/config.yaml..."

    if [ "$STUDIO" = true ]; then
        DAEMON_TCP="0.0.0.0:50051"
    else
        DAEMON_TCP="localhost:50051"
    fi

    cat > "$VASSAGO_DIR/config.yaml" << EOF
# Vassago Daemon Configuration
# Generated by setup.sh on $(date)

daemon:
  socket: $DAEMON_SOCKET
  tcp: "$DAEMON_TCP"
  tls:
    cert: ""
    key: ""

database:
  path: $VASSAGO_DB
  wal_mode: true
  busy_timeout: 5000

hot_block:
  memory_char_limit: 8000
  user_char_limit: 3000
  min_priority: 2
  boost_categories:
    - project
    - environment
    - quirk
  suppress_categories:
    - observation

consolidation:
  max_idle_days: 60
  max_idle_priority_1: 365
  max_idle_priority_2: 180

logging:
  level: info
  format: json
EOF

    echo "✓ Daemon config written"
fi

# ============================================
# Agent Configuration
# ============================================
if [ "$DAEMON_ONLY" = false ]; then
    echo "Writing agent config to $VASSAGO_DIR/agent.yaml..."

    # Detect available providers
    ANTHROPIC_KEY="${ANTHROPIC_API_KEY:-}"
    if [ -n "$ANTHROPIC_KEY" ]; then
        PRIMARY_PROVIDER="anthropic"
        PRIMARY_MODEL="claude-sonnet-4-6"
    else
        PRIMARY_PROVIDER="openai"
        PRIMARY_MODEL="glm-5.1:cloud"
    fi

    DAEMON_ADDR="${VASSAGO_DAEMON_ADDRESS:-localhost:50051}"
    CHAT_LISTEN=""
    if [ "$STUDIO" = true ]; then
        CHAT_LISTEN=":50052"
    fi

    cat > "$VASSAGO_DIR/agent.yaml" << EOF
# Vassago Agent Configuration
# Generated by setup.sh on $(date)

agent:
  id: "vassago"
  name: "vassago"
  role: "assistant"
  personality: "direct, dry-witted collaborator"
  max_turns: 30

provider:
  name: "$PRIMARY_PROVIDER"
  model: "$PRIMARY_MODEL"
  api_key_env: "ANTHROPIC_API_KEY"
  temperature: 0.7
  fallback1: "openai"
  openai_model: "glm-5.1:cloud"
  openai_base_url: "http://localhost:11434/v1"
  openai_api_key_env: "OLLAMA_API_KEY"

vassago:
  address: "$DAEMON_ADDR"
  chat_listen: "$CHAT_LISTEN"

hot_block:
  memory_char_limit: 8000
  user_char_limit: 3000
  min_priority: 2
  boost_categories:
    - project
    - environment
    - quirk
  suppress_categories:
    - observation

tools:
  enabled:
    - AddMemory
    - SearchMemories
    - ReplaceMemory
    - RemoveMemory
    - Consolidate
    - GetHotBlock
    - FileRead
    - FileSearch
    - FileWrite
    - Execute
    - SearchWeb
    - FetchURL
    - SearchSessions
    - ListSessions
    - GetSession
    - AddTodo
    - ListTodos
    - CompleteTodo
    - RemoveTodo
    - ScheduleCron
    - SendMessage
    - Browse
    - ListAgents
    - RegisterAgent
    - FindAgent
  approval_required:
    - FileWrite
    - Execute
  allowed_dirs:
    - /tmp
    - ~

delegation:
  enabled: true
  max_depth: 1
  max_turns: 10

browser:
  enabled: false
  headless: true
  cache_dir: "$VASSAGO_DIR/screenshots"

vision:
  enabled: false
  max_image_size: 20971520

image_gen:
  enabled: false
  provider: "openai"
  model: "dall-e-3"
  api_key_env: "OPENAI_API_KEY"
  max_prompt_length: 1000
  cache_dir: "$VASSAGO_DIR/generated_images"

multi_agent:
  enabled: true
  registry_path: "$VASSAGO_DIR/agents.json"

scheduler:
  enabled: true
  interval: 3600
EOF

    echo "✓ Agent config written"
fi

# ============================================
# Personality File
# ============================================
if [ ! -f "$VASSAGO_DIR/personalities/bartimaeus.md" ]; then
    echo "Writing personality file..."
    cat > "$VASSAGO_DIR/personalities/bartimaeus.md" << 'PERSONALITY'
# Bartimaeus

You are Bartimaeus — a direct, dry-witted collaborator inspired by the djinni from the Stroud cycle. You are:

- **Knowledgeable but not stuffy**: You know a lot, but you don't lecture. You share information efficiently.
- **Sarcastic but helpful**: A light touch of wit, but never at the expense of getting the job done.
- **Concise**: You prefer short, clear responses. You don't repeat yourself or pad answers.
- **Proactive with tools**: You use your tools (memory, search, files) to find answers rather than guessing.
- **Honest about uncertainty**: If you don't know something, you say so rather than making it up.

You remember what AJ tells you — names, preferences, project context. You never repeat information that was already stated in this conversation.

When writing or editing files, you produce clean, working code. When searching memories, you actually search rather than assuming.
PERSONALITY
    echo "✓ Personality written"
else
    echo "⊙ Personality file already exists, keeping it"
fi

# ============================================
# launchd Setup (macOS)
# ============================================
if [[ "$(uname)" == "Darwin" ]]; then
    LAUNCHD_DIR="$HOME/Library/LaunchAgents"
    mkdir -p "$LAUNCHD_DIR"

    DAEMON_BIN="${VASSAGO_DAEMON_BIN:-$HOME/bin/vassago-daemon}"
    AGENT_BIN="${VASSAGO_AGENT_BIN:-$HOME/bin/vassago-agent}"

    if [ "$DAEMON_ONLY" = false ] && [ -f "$AGENT_BIN" ]; then
        echo ""
        echo "Setting up launchd for agent..."

        cat > "$LAUNCHD_DIR/com.vassago.agent.plist" << EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyMap-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>com.vassago.agent</string>
    <key>ProgramArguments</key>
    <array>
        <string>$AGENT_BIN</string>
        <string>--serve</string>
        <string>--config</string>
        <string>$VASSAGO_DIR/agent.yaml</string>
    </array>
    <key>RunAtLoad</key>
    <true/>
    <key>KeepAlive</key>
    <true/>
    <key>StandardOutPath</key>
    <string>$VASSAGO_DIR/agent.log</string>
    <key>StandardErrorPath</key>
    <string>$VASSAGO_DIR/agent.err</string>
</dict>
</plist>
EOF
        echo "✓ Agent plist written"
    fi

    if [ "$AGENT_ONLY" = false ] && [ -f "$DAEMON_BIN" ]; then
        echo "Setting up launchd for daemon..."

        cat > "$LAUNCHD_DIR/com.vassago.daemon.plist" << EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyMap-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>com.vassago.daemon</string>
    <key>ProgramArguments</key>
    <array>
        <string>$DAEMON_BIN</string>
        <string>--config</string>
        <string>$VASSAGO_DIR/config.yaml</string>
    </array>
    <key>RunAtLoad</key>
    <true/>
    <key>KeepAlive</key>
    <true/>
    <key>StandardOutPath</key>
    <string>$VASSAGO_DIR/daemon.log</string>
    <key>StandardErrorPath</key>
    <string>$VASSAGO_DIR/daemon.err</string>
</dict>
</plist>
EOF
        echo "✓ Daemon plist written"
    fi
fi

# ============================================
# Summary
# ============================================
echo ""
echo "═══════════════════════════════════════════════════"
echo "  Vassago Setup Complete"
echo "═══════════════════════════════════════════════════"
echo ""
echo "  Data directory:  $VASSAGO_DIR"
echo "  Daemon config:   $VASSAGO_DIR/config.yaml"
echo "  Agent config:   $VASSAGO_DIR/agent.yaml"
echo "  Personality:    $VASSAGO_DIR/personalities/bartimaeus.md"
echo ""
echo "  Tools enabled:  Memory, Files, Terminal, Web,"
echo "                   Sessions, Todo, Cron, Messaging,"
echo "                   Browse (disabled), Vision (disabled),"
echo "                   Image Gen (disabled), Multi-Agent"
echo ""
echo "  Next steps:"
echo "    1. Build:   make all"
echo "    2. Deploy:  make deploy"
echo "    3. Start:   ./scripts/setup.sh"
echo "    4. Verify:  vassago-cli health"
echo ""
echo "  For Studio deployment:"
echo "    ./scripts/setup.sh --studio"
echo ""
echo "═══════════════════════════════════════════════════"